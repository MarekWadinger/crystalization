"""Watershed basin size vs its seed constants, 1080p clip 2026-02-05 10-36-32.

    uv run python scripts/watershed_seed_sweep.py [--video PATH] [--out docs/optics/watershed_seed_sweep.md]

Runs ``optics.detect_watershed.process_frame_watershed`` on frames 300, 750 and
1200 (``DEFAULT_CROP``, configured area window, the LayerConfig of
``scripts/rerun_paper_numbers.py``) with the seed constants
``_PEAK_MIN_DISTANCE`` / ``_PEAK_THRESHOLD_ABS`` at half, default and double
(6/3, 12/6, 24/12 px) and reports the median basin size (``Crystal.size``,
geometric mean of the basin's min-area-rect sides, clip px). If the median
follows the constants, the watershed CSD reports its seed spacing, not the
crystals (CLAIM_CHANGES item 18).
"""

from __future__ import annotations

import argparse
from pathlib import Path
from unittest.mock import patch

import cv2
import numpy as np

import optics.detect_watershed as ws
from annotator.types import LayerConfig
from optics.config import detection_area_px, lens_from_config, load_camera
from optics.video_io import DEFAULT_CROP

ROOT = Path(__file__).resolve().parents[1]
VIDEO = ROOT / "datasets" / "2026-02-05 10-36-32.mp4"
OUT = ROOT / "docs" / "optics" / "watershed_seed_sweep.md"
FRAMES = (300, 750, 1200)
SETTINGS = (
    (6, 3.0),
    (12, 6.0),
    (24, 12.0),
)  # (_PEAK_MIN_DISTANCE, _PEAK_THRESHOLD_ABS)


def layer_config() -> LayerConfig:
    """LayerConfig of the CSD runs, with the configured 1080p area window."""
    cfg = load_camera()
    min_area, max_area = detection_area_px(
        cfg, lens_from_config(cfg, 1920, 1080)
    )
    return LayerConfig(
        num_layers=3,
        sharpness_weight=0.7,
        flow_weight=0.3,
        blur_kernel=15,
        min_area=min_area,
        max_area=max_area,
        max_aspect_ratio=3.0,
    )


def read_gray(video: Path, idx: int) -> np.ndarray:
    cap = cv2.VideoCapture(str(video))
    try:
        cap.set(cv2.CAP_PROP_POS_FRAMES, idx)
        ok, frame = cap.read()
    finally:
        cap.release()
    if not ok:
        raise RuntimeError(f"cannot read frame {idx} of {video}")
    return cv2.cvtColor(DEFAULT_CROP.apply(frame), cv2.COLOR_BGR2GRAY)


def basin_sizes(gray: np.ndarray, idx: int, config: LayerConfig) -> np.ndarray:
    res, _ = ws.process_frame_watershed(gray, None, idx, config)
    return np.array([c.size for layer in res.layers for c in layer.crystals])


def sweep(video: Path) -> dict[tuple[int, float], dict[int, np.ndarray]]:
    config = layer_config()
    grays = {i: read_gray(video, i) for i in FRAMES}
    out: dict[tuple[int, float], dict[int, np.ndarray]] = {}
    for dist, thr in SETTINGS:
        with patch.multiple(
            ws, _PEAK_MIN_DISTANCE=dist, _PEAK_THRESHOLD_ABS=thr
        ):
            out[(dist, thr)] = {
                i: basin_sizes(g, i, config) for i, g in grays.items()
            }
    return out


def markdown(
    res: dict[tuple[int, float], dict[int, np.ndarray]], video: Path
) -> str:
    head = " | ".join(f"frame {i}: n / median" for i in FRAMES)
    lines = [
        "# Watershed basin size vs seed constants",
        "",
        "Generated by `uv run python scripts/watershed_seed_sweep.py`; do not edit.",
        "",
        f"Clip `{video.name}` (1080p DVR screen recording), frames "
        f"{', '.join(map(str, FRAMES))}, `DEFAULT_CROP`, configured area window "
        f"(`optics.config.detection_area_px`), all three sharpness layers pooled. "
        "Size = `Crystal.size`, the geometric mean of the basin's min-area-rect sides, "
        "in clip px. Defaults in `optics.detect_watershed`: 12 / 6.",
        "",
        f"| _PEAK_MIN_DISTANCE / _PEAK_THRESHOLD_ABS (px) | {head} | pooled n | pooled median (px) |",
        "|---|" + "---:|" * (len(FRAMES) + 2),
    ]
    for (dist, thr), per in res.items():
        cells = " | ".join(
            f"{len(s)} / {np.median(s):.1f}" for s in per.values()
        )
        pooled = np.concatenate(list(per.values()))
        lines.append(
            f"| {dist} / {thr:g} | {cells} | {len(pooled)} | {np.median(pooled):.1f} |"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    ap.add_argument("--video", type=Path, default=VIDEO)
    ap.add_argument("--out", type=Path, default=OUT)
    a = ap.parse_args()
    text = markdown(sweep(a.video), a.video)
    a.out.write_text(text)
    print(text)


if __name__ == "__main__":
    main()
