"""Sampling noise σ_w of the microscope anchor z_j = ln(median chord), 2026-10-30.

    uv run python scripts/microscope_anchor_noise.py [--out docs/softsensor/anchor_noise.md]

For each post-seeding microscope sample (``softsensor.data.microscope_samples``:
``datasets/microscope_annotations.csv``, one AI reading, pre-seeding b1-s02
excluded) the crystals are resampled with replacement within the sample and
σ_w is the standard deviation of ln(median) over the bootstrap draws. The
asymptotic value sqrt(π/2)·s_ln/sqrt(n), with s_ln the sample standard
deviation of ln(chord), is printed beside it as a check.

σ_w covers only which crystals the operator happened to measure. It does not
cover the operator's selection bias, the transcription, or the ±47 s clock.
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

import numpy as np

from softsensor.data import microscope_samples

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "softsensor" / "anchor_noise.md"
N_BOOT = 20_000
SEED = 20261030


def bootstrap_sigma_w(sizes_um: np.ndarray, rng: np.random.Generator) -> float:
    """Std of ln(median) over resamples of the crystals with replacement."""
    idx = rng.integers(0, len(sizes_um), size=(N_BOOT, len(sizes_um)))
    return float(np.log(np.median(sizes_um[idx], axis=1)).std(ddof=1))


def rows() -> list[tuple[str, float, int, float, float, float]]:
    """(sample, t_min, n, median µm, σ_w bootstrap, σ_w asymptotic) per sample."""
    rng = np.random.default_rng(SEED)
    out = []
    for samples in microscope_samples().values():
        for s in samples:
            n = len(s.sizes_um)
            s_ln = float(np.log(s.sizes_um).std(ddof=1)) if n > 1 else math.nan
            out.append(
                (
                    s.sample_id,
                    s.t_min,
                    n,
                    s.median_um,
                    bootstrap_sigma_w(s.sizes_um, rng),
                    math.sqrt(math.pi / 2) * s_ln / math.sqrt(n),
                )
            )
    return out


def markdown(table: list[tuple[str, float, int, float, float, float]]) -> str:
    boot = np.array([r[4] for r in table])
    lines = [
        "# Microscope anchor noise σ_w",
        "",
        "Generated by `uv run python scripts/microscope_anchor_noise.py`; do not edit.",
        "",
        "Anchor z_j = ln(median microscope chord) of sample j, 2026-10-30 sampled run "
        "(`datasets/microscope_annotations.csv`, one AI reading, pre-seeding b1-s02 "
        f"excluded). σ_w = std of ln(median) over {N_BOOT} bootstrap resamples of the "
        f"crystals within the sample (seed {SEED}); asymptotic = sqrt(π/2)·s_ln/sqrt(n). "
        "t = minutes since that strike's seeding.",
        "",
        "σ_w is the sampling noise of the measured crystals only. It leaves out the "
        "operator's choice of crystals, the transcription and the ±47 s clock.",
        "",
        "| sample | t (min) | n | median (µm) | σ_w bootstrap | σ_w asymptotic |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for sid, t, n, med, sb, sa in table:
        lines.append(
            f"| {sid} | {t:.0f} | {n} | {med:.0f} | {sb:.3f} | {sa:.3f} |"
        )
    lines += [
        "",
        f"{len(boot)} samples; bootstrap σ_w median {np.median(boot):.3f}, "
        f"range {boot.min():.3f}–{boot.max():.3f}.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    ap.add_argument("--out", type=Path, default=OUT)
    a = ap.parse_args()
    text = markdown(rows())
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(text)
    print(text)


if __name__ == "__main__":
    main()
